def college_name(code: str | None) -> str | None:
    """学院码 → 学院名。查不到返回 None，让调用方决定显示什么。"""
    if not code:
        return None
    return COLLEGES.get(code)


def major_name(college: str | None, major: str | None) -> str | None:
    """(学院码, 专业号) → 专业名。"""
    if not college or not major:
        return None
    return MAJORS.get((college, major))


