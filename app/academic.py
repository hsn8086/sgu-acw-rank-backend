def short_college(name: str | None) -> str:
    """学院名转简称。认不出就原样返回。"""
    if not name:
        return ""
    return COLLEGE_SHORT.get(name, name)


def short_major(name: str | None) -> str:
    """专业名转简称。

    先直接查，查不到再去掉括号后缀查一次（「临床医学(本科)」→「临床医学」，
    「护理(专科)」→「护理」）。还查不到就原样返回，不硬截。
    """
    if not name:
        return ""
    if name in MAJOR_SHORT:
        return MAJOR_SHORT[name]

    # 去掉括号后缀，注意有全角和半角两种。
    stripped = re.sub(r"[（(].*$", "", name).strip()
    return MAJOR_SHORT.get(stripped, name)
